// Writes docs/MCP-SONG-FORMAT.md from src/ui/mcp-guide.js: the song file format and the example, for a
// person to give ChatGPT (or any AI without the MCP server). --check fails when the file is out of date
// (tests/song-spec.test.mjs runs the same check).
//
// Revision history
//   0.1.0  2026-11-20  First version (fork, MCP server work).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { SONG_EXAMPLE, SONG_GUIDE } from '../src/ui/mcp-guide.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const FILE = path.join(ROOT, 'docs', 'MCP-SONG-FORMAT.md');

export function songFormatDoc() {
  return `# Writing an MC-707 song with ChatGPT (or any AI)

GENERATED by scripts/mcp-song-format.mjs from src/ui/mcp-guide.js: do not edit.

Give the AI everything below the line, then ask for a song. Save its answer as a \`.json\` file and open
it in the Toolbox with File > Open. Then File > Save as MC-707 project (or ask Claude, through the MCP
server, to save it to the card). Errors are listed when the file opens; nothing changes if there are any.

Ask it to answer with the JSON only, in one code block.

---

You write songs for a Roland MC-707 as one JSON file in the format below. Answer with the JSON only.

\`\`\`text
${SONG_GUIDE}
\`\`\`

A complete, valid example:

\`\`\`json
${JSON.stringify(SONG_EXAMPLE, null, 1)}
\`\`\`
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const want = songFormatDoc();
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8') : '';
    if (have !== want) {
      console.error('docs/MCP-SONG-FORMAT.md is out of date: run node scripts/mcp-song-format.mjs');
      process.exit(1);
    }
    console.log('docs/MCP-SONG-FORMAT.md is up to date');
  } else {
    fs.writeFileSync(FILE, want);
    console.log('Wrote docs/MCP-SONG-FORMAT.md');
  }
}
